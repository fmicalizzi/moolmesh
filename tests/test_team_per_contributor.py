class TestGoldenOff:
    """Option off → byte-identical to the pre-#83 output."""

    @pytest.mark.parametrize("name", list(OFF_CONFIGS))
    def test_surfaces_match_pre_change_golden(self, name, tmp_path, utc_system,
                                              config_file, fixed_states):
        config_file(OFF_CONFIGS[name])
        fx = _build(tmp_path)
        try:
            out = _surfaces(fx)
        finally:
            fx["store"].close()
        if REGEN and name == "absent":
            GOLDEN.mkdir(parents=True, exist_ok=True)
            for fname, text in out.items():
                (GOLDEN / f"per_contributor_off_{fname}").write_text(
                    text, encoding="utf-8")
        for fname, text in out.items():
            want = (GOLDEN / f"per_contributor_off_{fname}").read_text(
                encoding="utf-8")
            assert text == want, f"{fname} changed with the option {name}"
