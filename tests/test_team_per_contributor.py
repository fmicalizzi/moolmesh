def _mkrepo(base: Path) -> Path:
    repo = base / "acme-api"
    (repo / ".git").mkdir(parents=True)
    (repo / ".git" / "config").write_text(
        '[remote "origin"]\n\turl = git@github.com:acme/api.git\n', encoding="utf-8")
    return repo


def _build(tmp_path):
    """workspace.db with one session on proj:acme + github.db (real schema)."""
    from hub.cache.git_store import GitStore
    from hub.cache.workspace_store import WorkspaceStore
    from hub.config import RepoConfig
    from hub.correlation.workspace_resolver import resolve_dir, resolve_path

    repo = _mkrepo(tmp_path)
    ws = WorkspaceStore(tmp_path / "workspace.db")
    key = resolve_dir(str(repo)).key
    with ws._lock:
        ws._upsert_workspace_locked(resolve_dir(str(repo)), "2026-01-01T00:00:00")
        wid = ws._conn.execute(
            "SELECT id FROM workspaces WHERE workspace_key=?", (key,)).fetchone()[0]
        ws._conn.execute(
            """INSERT OR REPLACE INTO workspace_classification
               (workspace_id, category, subtype, role, project_key,
                project_label, resolved_via, classified_at)
               VALUES (?,?,?,?,?,?,?,?)""",
            (wid, "A", "project", "project", "proj:acme", "acme", "self",
             "2026-01-01T00:00:00"))
        ws._conn.commit()
    f = str(repo / "src" / "x.py")
    ws.record_attribution("sess1", "claude", f, resolve_path(f))
    with ws._lock:
        ws._conn.execute("UPDATE path_attributions SET activity_ts = ?",
                         ("2026-05-05T12:00:00+00:00",))
        ws._conn.commit()
    ws.close()

    gs = GitStore(tmp_path / "github.db")
    rid = gs.register_repo(RepoConfig(
        path=str(repo), remote_url="github.com/acme/api", owner="acme",
        repo="api", added_at="2026-01-01T00:00:00"))
    gs.upsert_issues(rid, ISSUES)
    gs.upsert_pr_stats(rid, PR_STATS)
    gs.store_commits(rid, COMMITS)
    ev = tmp_path / "events.db"
    sqlite3.connect(ev).close()
    return {"events": str(ev), "workspace": str(tmp_path / "workspace.db"),
            "github": str(tmp_path / "github.db"), "store": gs, "repo_id": rid}


def _portfolio(fx):
    from hub.mcp_server import _portfolio_production
    import zoneinfo
    return _portfolio_production(
        fx["events"], fx["workspace"], days=7, today=TODAY, hide=False,
        github_db=fx["github"], tz=zoneinfo.ZoneInfo("UTC"))


def _digests(fx):
    from hub.digests.engine import DigestEngine
    engine = DigestEngine(fx["store"])
    daily = engine.get_daily_digest(fx["repo_id"], DAILY, repo_name="acme/api",
                                    force_refresh=True)
    weekly = engine.get_weekly_digest(fx["repo_id"], WEEK, repo_name="acme/api",
                                      force_refresh=True)
    return daily, weekly


def _surfaces(fx) -> dict[str, str]:
    """Every touched surface, serialized the way it leaves MoolMesh."""
    daily, weekly = _digests(fx)
    return {
        # /api/workspace/portfolio/production serializes with json.dumps(data).
        "portfolio_production.json": json.dumps(_portfolio(fx)),
        "digest_daily.json": json.dumps(daily, ensure_ascii=False, indent=1),
        "digest_weekly.json": json.dumps(weekly, ensure_ascii=False, indent=1),
    }


